"""Standalone consolidation ROI evaluation module for Study 08.

Extracts the Phase C consolidation evaluation from runner.py so it can be
imported and called programmatically without the full CLI orchestrator.

"Consolidation ROI" measures whether running the Curator's LLM Phase 2
(merge / split suggestions) actually improves Library Coverage, and at what
minimum library size the improvement becomes reliable.

Usage::

    from phase_4_dynamics.study_08_library_dynamics.consolidation_eval import evaluate_consolidation_roi

    roi_records = await evaluate_consolidation_roi(
        skills_root=path_to_library,
        target_sizes=[10, 25, 50, 100],
        model="openai/gpt-4o-mini",
        dry_run=False,
        task_queries=queries,
    )
    for r in roi_records:
        print(f"size≈{r.target_size}  ΔLC={r.lc_delta:+.3f}  suggestions={r.suggestions_count}")
"""
from __future__ import annotations

import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional

from shared.result_logger import ResultLogger
from phase_4_dynamics.study_08_library_dynamics.coverage_metric import compute_library_coverage


# Minimum positive ΔLC to call a consolidation run "beneficial"
LC_BENEFIT_THRESHOLD = 0.005


@dataclass
class ConsolidationROIRecord:
    """Metrics from one consolidation evaluation checkpoint."""

    target_size: int
    """The approximate library size at which this evaluation was performed."""

    actual_n_skills: int
    """Actual number of skills found in the library at evaluation time."""

    lc_before: float
    """Library Coverage before running LLM consolidation."""

    lc_after: float
    """Library Coverage after running LLM consolidation."""

    lc_delta: float
    """``lc_after - lc_before`` (positive = consolidation helped)."""

    redundancy_before: float
    """Mean pairwise cosine similarity before consolidation."""

    redundancy_after: float
    """Mean pairwise cosine similarity after consolidation."""

    suggestions_count: int
    """Number of merge/split suggestions generated by Phase 2."""

    is_beneficial: bool
    """True if ``lc_delta >= LC_BENEFIT_THRESHOLD``."""

    run_id: str = ""

    def __post_init__(self) -> None:
        if not self.run_id:
            self.run_id = f"consol_size{self.target_size}_{uuid.uuid4().hex[:6]}"


async def evaluate_consolidation_roi(
    skills_root: Path,
    target_sizes: List[int],
    model: str,
    dry_run: bool,
    task_queries: List[str],
    logger: Optional[ResultLogger] = None,
) -> List[ConsolidationROIRecord]:
    """Evaluate LLM-consolidation ROI at several library size checkpoints.

    For each size in *target_sizes*:
      1. Measure LC before consolidation.
      2. Run Curator Phase 2 (LLM merge/split) if not dry_run.
      3. Measure LC after consolidation.
      4. Record ΔLC and suggestion count.

    Sizes for which the library does not yet have enough skills are skipped.

    Args:
        skills_root:  Root directory of the skill library (contains SKILL.md files).
        target_sizes: Approximate skill counts at which to evaluate.
        model:        litellm model string used for Phase 2 consolidation.
        dry_run:      If True, skip real LLM calls; return stub delta of 0.
        task_queries: Task queries used for LC computation (first 10 used).
        logger:       Optional ``ResultLogger``; if provided, records are logged.

    Returns:
        List of ``ConsolidationROIRecord`` in target_size order.
    """
    from skilltend.config import ReviewerConfig  # type: ignore[import]
    from skilltend.curator.curator import _run_phase2  # type: ignore[import]

    eval_queries = task_queries[:10]
    results: List[ConsolidationROIRecord] = []

    for size in sorted(target_sizes):
        skill_paths = list(skills_root.rglob("SKILL.md"))
        actual_n = len(skill_paths)

        if actual_n < size:
            print(f"  Skipping size={size}: only {actual_n} skills in library")
            continue

        coverage_before = await compute_library_coverage(
            skills_root, eval_queries, dry_run=dry_run
        )

        suggestions_count = 0
        if not dry_run:
            config = ReviewerConfig(
                skills_root=skills_root,
                curator_llm_consolidation=True,
                curator_consolidation_model=model,
            )
            try:
                suggestions = await _run_phase2(config, model)
                suggestions_count = len(suggestions)
            except Exception as exc:
                print(f"  Phase 2 error at size={size}: {exc}")

        coverage_after = await compute_library_coverage(
            skills_root, eval_queries, dry_run=dry_run
        )

        lc_delta = round(coverage_after["lc"] - coverage_before["lc"], 4)
        rec = ConsolidationROIRecord(
            target_size=size,
            actual_n_skills=actual_n,
            lc_before=coverage_before["lc"],
            lc_after=coverage_after["lc"],
            lc_delta=lc_delta,
            redundancy_before=coverage_before["mean_pairwise_sim"],
            redundancy_after=coverage_after["mean_pairwise_sim"],
            suggestions_count=suggestions_count,
            is_beneficial=lc_delta >= LC_BENEFIT_THRESHOLD,
        )
        results.append(rec)

        if logger is not None:
            logger.log(
                run_id=rec.run_id,
                config={"phase": "C_consolidation", "target_size": size},
                metrics={
                    "lc_before": rec.lc_before,
                    "lc_after": rec.lc_after,
                    "lc_delta": rec.lc_delta,
                    "redundancy_before": rec.redundancy_before,
                    "redundancy_after": rec.redundancy_after,
                    "suggestions_count": rec.suggestions_count,
                    "n_skills": rec.actual_n_skills,
                },
            )

        symbol = "+" if rec.is_beneficial else " "
        print(
            f"  [{symbol}] size≈{size:4d}  "
            f"LC: {rec.lc_before:.3f}→{rec.lc_after:.3f} (Δ{rec.lc_delta:+.3f})  "
            f"redundancy: {rec.redundancy_before:.3f}→{rec.redundancy_after:.3f}  "
            f"suggestions={rec.suggestions_count}"
        )

    return results


def minimum_beneficial_size(records: List[ConsolidationROIRecord]) -> Optional[int]:
    """Return the smallest library size at which consolidation was beneficial.

    Returns None if no beneficial size was found.
    """
    for rec in sorted(records, key=lambda r: r.target_size):
        if rec.is_beneficial:
            return rec.target_size
    return None


def format_roi_table(records: List[ConsolidationROIRecord]) -> str:
    """Format consolidation ROI records as a human-readable table."""
    if not records:
        return "No consolidation records."
    lines = [
        f"{'Size':>6}  {'Skills':>6}  {'LC Before':>9}  {'LC After':>9}  "
        f"{'ΔLC':>7}  {'Suggestions':>11}  {'Beneficial':>10}"
    ]
    lines.append("-" * 70)
    for r in sorted(records, key=lambda x: x.target_size):
        flag = "YES" if r.is_beneficial else "no"
        lines.append(
            f"{r.target_size:>6}  {r.actual_n_skills:>6}  {r.lc_before:>9.3f}  "
            f"{r.lc_after:>9.3f}  {r.lc_delta:>+7.3f}  {r.suggestions_count:>11}  {flag:>10}"
        )
    return "\n".join(lines)
